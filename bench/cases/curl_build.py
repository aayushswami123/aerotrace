"""The fixed curl 8.23.0 build used by the benchmark: configure options, and compile_commands.json.

curl needs `./configure` to write lib/curl_config.h. We run it once, in a temp copy of the pinned
tarball (never in anyone's own tree), with a fixed, minimal option set that doesn't depend on what is
installed on the machine: no TLS, no HTTP/2 or HTTP/3, no compression, no SSH, no LDAP.

Usage:
  python3 -I bench/cases/curl_build.py configure <curl-root>   # runs ./configure with CONFIGURE_ARGS
  python3 -I bench/cases/curl_build.py compdb <curl-root>      # writes <curl-root>/compile_commands.json

The compile flags are copied from the Makefiles that configure generates (lib/Makefile and
src/Makefile: DEFS, AM_CPPFLAGS, the active am__append_* flags, libcurl_la_CPPFLAGS, curl_CPPFLAGS, CFLAGS). The file lists come from lib/Makefile.inc (CSOURCES) and
src/Makefile.inc (CURL_CFILES, CURLX_CFILES): the `curl` program and the libcurl it links.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

CONFIGURE_ARGS = [
    "--disable-shared", "--enable-static",
    "--without-ssl", "--without-zlib", "--without-brotli", "--without-zstd",
    "--without-libpsl", "--without-libidn2",
    "--without-nghttp2", "--without-nghttp3", "--without-ngtcp2",
    "--without-libssh2", "--without-libssh", "--without-librtmp", "--without-libgsasl", "--without-gssapi",
    "--disable-ldap", "--disable-ldaps",
    "--without-ca-bundle", "--without-ca-path",
]  # fmt: skip
CFLAGS = [
    "-Qunused-arguments",
    "-Werror-implicit-function-declaration",
    "-O2",
    "-Werror=partial-availability",
]


def make_list(path: Path, names: list[str]) -> list[str]:
    """Expand `NAME = a b \\` lists from a Makefile.inc (only the variables asked for, and $(REFS) to them)."""
    text = path.read_text().replace("\\\n", " ")
    vars_: dict[str, list[str]] = {}
    for m in re.finditer(r"^([A-Z_]+)\s*=(.*)$", text, re.M):
        vars_[m.group(1)] = m.group(2).split()

    def expand(name: str) -> list[str]:
        out: list[str] = []
        for w in vars_.get(name, []):
            ref = re.fullmatch(r"\$\(([A-Z_]+)\)", w)
            out += expand(ref.group(1)) if ref else [w]
        return out

    files: list[str] = []
    for n in names:
        files += expand(n)
    return [f for f in files if f.endswith(".c")]


def configure(root: Path) -> None:
    subprocess.run(["./configure", *CONFIGURE_ARGS], cwd=root, check=True, capture_output=True)


def write_compdb(root: Path) -> list[dict]:
    if not (root / "lib" / "curl_config.h").exists():
        raise SystemExit("lib/curl_config.h is missing: run `curl_build.py configure` first")
    entries = []
    lib = root / "lib"
    for f in sorted(set(make_list(lib / "Makefile.inc", ["CSOURCES"]))):
        args = [
            "cc",
            "-DHAVE_CONFIG_H",
            "-I../include",
            "-I.",
            "-DBUILDING_LIBCURL",
            "-DCURL_STATICLIB",
            "-DCURL_HIDDEN_SYMBOLS",
            "-fvisibility=hidden",
            *CFLAGS,
            "-c",
            f,
        ]  # lib/Makefile am__append_8/10/11
        entries.append({"directory": str(lib), "file": f, "arguments": args})
    src = root / "src"
    for f in sorted(set(make_list(src / "Makefile.inc", ["CURL_CFILES", "CURLX_CFILES"]))):
        if not (src / f).exists():
            continue  # generated by the build (tool_hugehelp.c and friends); not part of the scan
        args = [
            "cc",
            "-DHAVE_CONFIG_H",
            "-I../include",
            "-I../lib",
            "-I.",
            "-DCURL_STATICLIB",
            "-DUSE_MANUAL",
            *CFLAGS,
            "-c",
            f,
        ]  # src/Makefile am__append_1 and curl_CPPFLAGS (am__append_6)
        entries.append({"directory": str(src), "file": f, "arguments": args})
    (root / "compile_commands.json").write_text(json.dumps(entries, indent=1))
    return entries


if __name__ == "__main__":
    cmd, where = sys.argv[1], Path(sys.argv[2]).resolve()
    if cmd == "configure":
        configure(where)
    elif cmd == "compdb":
        print(f"{len(write_compdb(where))} entries")
    else:
        raise SystemExit("usage: curl_build.py configure|compdb <curl-root>")
